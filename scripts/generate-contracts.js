#!/usr/bin/env node
// Generate TypeScript models and OpenAPI from the canonical schema and routes.
const fs = require("node:fs/promises");
const path = require("node:path");
const prettier = require("prettier");
const Ajv2020 = require("ajv/dist/2020").default;
const standaloneCode = require("ajv/dist/standalone").default;
const { routes, parameters } = require("../src/api-contract");
const config = require("../src/config");

const root = path.resolve(__dirname, "..");

function typeFor(schema, indent = 0) {
  if (schema.$ref) return schema.$ref.split("/").at(-1);
  if (Object.hasOwn(schema, "const")) return JSON.stringify(schema.const);
  if (schema.enum)
    return schema.enum.map((item) => JSON.stringify(item)).join(" | ");
  if (Array.isArray(schema.type)) {
    return schema.type
      .map((kind) => typeFor({ ...schema, type: kind }, indent))
      .join(" | ");
  }
  if (schema.type === "integer" || schema.type === "number") return "number";
  if (["string", "boolean", "null"].includes(schema.type)) return schema.type;
  if (schema.type === "array") return `Array<${typeFor(schema.items, indent)}>`;
  if (schema.type === "object") {
    const entries = Object.entries(schema.properties || {});
    if (!entries.length) {
      if (schema.additionalProperties === false) return "Record<string, never>";
      return `Record<string, ${typeof schema.additionalProperties === "object" ? typeFor(schema.additionalProperties, indent) : "unknown"}>`;
    }
    const required = new Set(schema.required || []);
    const pad = " ".repeat(indent + 2);
    const fields = entries.map(
      ([name, value]) =>
        `${pad}${JSON.stringify(name)}${required.has(name) ? "" : "?"}: ${typeFor(value, indent + 2)};`,
    );
    if (schema.additionalProperties !== false) {
      const value =
        typeof schema.additionalProperties === "object"
          ? typeFor(schema.additionalProperties, indent + 2)
          : "unknown";
      fields.push(`${pad}[key: string]: ${value};`);
    }
    return `{\n${fields.join("\n")}\n${" ".repeat(indent)}}`;
  }
  throw new Error(
    `Unsupported schema for TypeScript generation: ${JSON.stringify(schema)}`,
  );
}

function typescript(schema) {
  const declarations = Object.entries(schema.$defs).map(
    ([name, definition]) => `export type ${name} = ${typeFor(definition)};`,
  );
  return `// Generated by scripts/generate-contracts.js from schemas/geo-data.schema.json. Do not edit.\n\n${declarations.join("\n\n")}\n`;
}

function openapi(schema) {
  const paths = {};
  for (const route of routes) {
    if (!schema.$defs[route.response])
      throw new Error(`Unknown response schema: ${route.response}`);
    const names = [...route.path.matchAll(/\{([^}]+)\}/g)].map(
      (match) => match[1],
    );
    const params = names.map((name) => {
      if (!parameters[name]) throw new Error(`Unknown path parameter: ${name}`);
      return { name, in: "path", required: true, ...parameters[name] };
    });
    const operation = {
      operationId: route.operationId,
      tags: [route.group],
      summary: route.summary,
      ...(route.description ? { description: route.description } : {}),
      ...(route.condition
        ? {
            "x-availability":
              "Generated only when source city timezone data exists.",
          }
        : {}),
      ...(params.length ? { parameters: params } : {}),
      responses: {
        200: {
          description: "Generated JSON file",
          content: {
            "application/json": {
              schema: {
                $ref: `./schemas/geo-data.schema.json#/$defs/${route.response}`,
              },
            },
          },
        },
        404: {
          description:
            "The file does not exist; the static host controls the error response.",
        },
      },
    };
    if (paths[`/${route.path}`])
      throw new Error(`Duplicate route: ${route.path}`);
    paths[`/${route.path}`] = { get: operation };
  }
  return {
    openapi: "3.1.0",
    info: {
      title: "Geo-Data API",
      version: "v2",
      description:
        "Static country, state, and city files. Resource responses use data and meta; discovery, manifest, and build-report files have their own top-level structures.",
    },
    servers: [
      {
        url: config.CDN_BASE_URL,
        description: "Example CDN base URL; deployments can use another host.",
      },
    ],
    paths,
  };
}

async function main() {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== "--check"))
    throw new Error("Usage: node scripts/generate-contracts.js [--check]");
  const check = args.includes("--check");
  const schema = JSON.parse(
    await fs.readFile(path.join(root, "schemas/geo-data.schema.json"), "utf8"),
  );
  const modelTypes = await prettier.format(typescript(schema), {
    parser: "typescript",
  });
  const processorTypes = await prettier.format(
    `${modelTypes}\n/** Programmatic builds share generator configuration; run builds sequentially. */\nexport interface ProcessorOptions { inputDir?: string; outputDir?: string; pretty?: boolean; compress?: boolean; compressionThreshold?: number; countryShardSize?: number; }\nexport class DataProcessor { constructor(options?: ProcessorOptions); run(): Promise<unknown>; }\n`,
    { parser: "typescript" },
  );
  const api = await prettier.format(JSON.stringify(openapi(schema)), {
    parser: "json",
  });
  const ajv = new Ajv2020({ code: { source: true }, strict: false });
  ajv.addSchema(schema);
  const schemaRefs = Object.fromEntries(
    Object.keys(schema.$defs).map((name) => [
      name,
      `${schema.$id}#/$defs/${name}`,
    ]),
  );
  const validators = `// Generated from schemas/geo-data.schema.json. Do not edit.\n${standaloneCode(ajv, schemaRefs)}\n`;
  const files = new Map([
    ["openapi.json", api],
    ["types/index.d.ts", processorTypes],
    ["packages/client/models.d.ts", modelTypes],
    ["src/generated/validators.js", validators],
  ]);
  const stale = [];
  for (const [name, contents] of files) {
    const filename = path.join(root, name);
    if (check) {
      let existing;
      try {
        existing = await fs.readFile(filename, "utf8");
      } catch (error) {
        if (error.code !== "ENOENT") throw error;
      }
      if (existing !== contents) stale.push(name);
    } else {
      await fs.mkdir(path.dirname(filename), { recursive: true });
      await fs.writeFile(filename, contents);
    }
  }
  if (stale.length)
    throw new Error(
      `Generated contracts are stale: ${stale.join(", ")}. Run node scripts/generate-contracts.js`,
    );
  console.log(
    check
      ? "Generated contracts are current."
      : "Generated OpenAPI and TypeScript contracts.",
  );
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
