const fs = require("fs");
const fsp = fs.promises;
const path = require("path");

const projectRoot = path.resolve(__dirname, "../");
const sourceDir = path.join(
  projectRoot,
  "node_modules",
  "flag-icons",
  "flags",
  "4x3",
);
const sourceLicense = path.join(
  projectRoot,
  "node_modules",
  "flag-icons",
  "LICENSE",
);
const assetsDir = path.join(projectRoot, "playground", "assets");
const flagsDir = path.join(assetsDir, "flags", "4x3");
const cssPath = path.join(assetsDir, "flag-icons.css");
const noticePath = path.join(projectRoot, "NOTICE-flag-icons.txt");

function readCountryCodes() {
  const raw = fs.readFileSync(
    path.join(projectRoot, "db", "countries.json"),
    "utf8",
  );
  const countries = JSON.parse(raw);
  const list = Array.isArray(countries) ? countries : countries.data || [];
  return [
    ...new Set(list.map((country) => String(country.iso2).toLowerCase())),
  ].sort();
}

function readPackageVersion() {
  const pkg = JSON.parse(
    fs.readFileSync(
      path.join(projectRoot, "node_modules", "flag-icons", "package.json"),
      "utf8",
    ),
  );
  return pkg.version;
}

function buildCss(codes, version) {
  const lines = [
    "/*",
    " * Country flag icons for the demo.",
    ` * Source: flag-icons ${version} (https://github.com/lipis/flag-icons)`,
    " * License: MIT (see NOTICE-flag-icons.txt)",
    " * Copyright (c) 2013 Panayiotis Lipiridis",
    " *",
    " * Generated by scripts/vendor-flags.js from db/countries.json.",
    " * Do not edit by hand; run `npm run vendor:flags` to regenerate.",
    " */",
    "",
    ".fi {",
    "  display: inline-block;",
    "  width: 1.333333em;",
    "  height: 1em;",
    "  background-position: 50%;",
    "  background-repeat: no-repeat;",
    "  background-size: contain;",
    "  border-radius: 2px;",
    "  box-shadow: 0 0 0 1px rgb(0 0 0 / 0.08);",
    "  flex: none;",
    "  vertical-align: -0.125em;",
    "}",
    "",
  ];

  for (const code of codes) {
    lines.push(
      `.fi-${code} { background-image: url("flags/4x3/${code}.svg"); }`,
    );
  }

  return `${lines.join("\n")}\n`;
}

async function main() {
  if (!fs.existsSync(sourceDir)) {
    throw new Error(
      "flag-icons is not installed. Run `npm install` before vendoring flags.",
    );
  }

  const codes = readCountryCodes();
  const version = readPackageVersion();
  const missing = codes.filter(
    (code) => !fs.existsSync(path.join(sourceDir, `${code}.svg`)),
  );
  if (missing.length) {
    throw new Error(
      `flag-icons ${version} is missing flags for: ${missing.join(", ")}`,
    );
  }

  await fsp.rm(flagsDir, { recursive: true, force: true });
  await fsp.mkdir(flagsDir, { recursive: true });

  let bytes = 0;
  for (const code of codes) {
    const from = path.join(sourceDir, `${code}.svg`);
    const to = path.join(flagsDir, `${code}.svg`);
    await fsp.copyFile(from, to);
    bytes += (await fsp.stat(to)).size;
  }

  await fsp.writeFile(cssPath, buildCss(codes, version));

  const license = await fsp.readFile(sourceLicense, "utf8");
  await fsp.writeFile(
    noticePath,
    [
      "flag-icons",
      `Version ${version}`,
      "https://github.com/lipis/flag-icons",
      "",
      "The SVG flag files in playground/assets/flags/4x3/ are unmodified",
      "copies of the flag-icons 4x3 set. The generated stylesheet in",
      "playground/assets/flag-icons.css is derived from the same source.",
      "",
      "----------------------------------------------------------------------",
      "",
      license.trimEnd(),
      "",
    ].join("\n"),
  );

  console.log(
    `✓ Vendored ${codes.length} flags (${(bytes / 1024).toFixed(0)} KB) into ${path.relative(projectRoot, flagsDir)}`,
  );
  console.log(`✓ Wrote ${path.relative(projectRoot, cssPath)}`);
  console.log(`✓ Wrote ${path.relative(projectRoot, noticePath)}`);
}

main().catch((error) => {
  console.error(`✗ ${error.message}`);
  process.exitCode = 1;
});
